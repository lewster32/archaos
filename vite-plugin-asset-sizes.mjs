import { writeFileSync, statSync, readdirSync } from "fs";
import { join } from "path";

/**
 * Assets explicitly loaded by GameScene.preload() via Phaser's loader.
 * Update this list if preload() gains or loses files.
 */
const PHASER_ASSET_FILES = new Set([
    "classicunits.png",
    "classicunits.json",
    "board.png",
    "board.json",
    "cursors.png",
    "cursors.json",
    "effects.png",
    "effects.json",
    "wizards.png",
    "magic-armour.png",
    "hats.png",
    "unit-glow.png",
    "chaossounds.json",
    "rexcolorreplacepipelineplugin.min.js",
    "rexperlinplugin.min.js",
]);

/**
 * Audio formats in preference order.
 * The browser downloads exactly one format per audio sprite; we count the
 * first format found so the estimate stays conservative.
 */
const AUDIO_FORMAT_PREFERENCE = [".ogg", ".mp3", ".m4a"];

/** Returns the preferred audio filename for a stem, or null if none found. */
function preferredAudioFile(stem, files) {
    for (const ext of AUDIO_FORMAT_PREFERENCE) {
        const candidate = `${stem}${ext}`;
        if (files.includes(candidate)) return candidate;
    }
    return null;
}

/**
 * JS files produced by the entry bundle that load before the loading screen
 * appears and therefore should NOT be counted.
 */
const JS_EXCLUDE = new Set([
    "index.js",
    "rolldown-runtime.js",
    // Rex plugins are already counted as Phaser assets above.
    "rexcolorreplacepipelineplugin.min.js",
    "rexperlinplugin.min.js",
]);

/**
 * CSS files that are part of the initial (pre-loading-screen) bundle and
 * therefore should NOT be counted.  Lazy CSS chunks (e.g. Game.css) are
 * fetched alongside their JS counterpart after the loading screen appears
 * and ARE counted.
 */
const CSS_EXCLUDE = new Set(["index.css"]);

/**
 * Vite plugin: after each production build, calculates the total byte size of
 * all assets the browser fetches after the loading screen first appears:
 *   - Lazy JS bundles  (Game.js, phaser.js, …)
 *   - Phaser preload assets  (spritesheets, audio, plugins)
 *
 * Writes the result to src/game/asset-sizes.ts so LoadingScreen.vue can
 * display an accurate "X of Y MB" label without any runtime measurement.
 *
 * @returns {import('vite').Plugin}
 */
export function phaserAssetSizesPlugin() {
    let outDir = "dist";

    return {
        name: "phaser-asset-sizes",
        apply: "build",

        configResolved(config) {
            outDir = config.build.outDir;
        },

        closeBundle() {
            const assetsDir = join(process.cwd(), outDir, "assets");

            let files;
            try {
                files = readdirSync(assetsDir);
            } catch {
                return; // dist/assets doesn't exist yet
            }

            const sizeOf = (name) => statSync(join(assetsDir, name)).size;

            let total = 0;
            const counted = [];

            // --- Phaser preload assets ---
            for (const file of files) {
                if (PHASER_ASSET_FILES.has(file)) {
                    const size = sizeOf(file);
                    total += size;
                    counted.push({ file, size, note: "Phaser preload" });
                }
            }

            // --- Audio: one format per stem ---
            const audioFiles = files.filter((f) => /\.(ogg|mp3|m4a)$/.test(f));
            const audioStems = new Set(
                audioFiles.map((f) => f.replace(/\.(ogg|mp3|m4a)$/, "")),
            );
            for (const stem of audioStems) {
                const file = preferredAudioFile(stem, files);
                if (file) {
                    const size = sizeOf(file);
                    total += size;
                    counted.push({ file, size, note: "audio (preferred format)" });
                }
            }

            // --- Lazy CSS bundles (fetched alongside their JS chunk) ---
            for (const file of files) {
                if (file.endsWith(".css") && !CSS_EXCLUDE.has(file)) {
                    const size = sizeOf(file);
                    total += size;
                    counted.push({ file, size, note: "lazy CSS bundle" });
                }
            }

            // --- Lazy JS bundles (fetched after the loading screen appears) ---
            for (const file of files) {
                if (file.endsWith(".js") && !JS_EXCLUDE.has(file)) {
                    const size = sizeOf(file);
                    total += size;
                    counted.push({ file, size, note: "lazy JS bundle" });
                }
            }

            const lines = [
                "// THIS FILE IS AUTO-GENERATED by vite-plugin-asset-sizes.mjs.",
                "// Run `npm run build` to update. Do not edit manually.",
                "//",
                "// Assets counted (bytes, uncompressed):",
                ...counted.map(
                    ({ file, size, note }) =>
                        `//   ${file.padEnd(48)} ${String(size).padStart(9)} B  (${note})`,
                ),
                `//   ${"TOTAL".padEnd(48)} ${String(total).padStart(9)} B`,
                "",
                "/** Total uncompressed bytes fetched by the browser after the loading screen appears. */",
                `export const TOTAL_GAME_ASSET_BYTES = ${total};`,
                "",
            ];

            writeFileSync(
                join(process.cwd(), "src/game/asset-sizes.ts"),
                lines.join("\n"),
            );
            console.info(
                `\n[phaser-asset-sizes] Counted ${counted.length} assets — ` +
                    `total ${(total / 1024 / 1024).toFixed(2)} MB`,
            );
        },
    };
}
