/**
 * Enumeration for different types of unit attacks.
 */
export enum UnitAttackType {
    /**
     * Standard melee attack.
     */
    Attacked = "attacked",

    /**
     * Burned attack type (e.g., dragon breath).
     */
    Burned = "burned",

    /**
     * Engulfed attack type (e.g., gooey blob)
     */
    Engulfed = "engulfed",
}
